CREATE OR REPLACE FUNCTION "public"."match_chunks"("query_embedding" "public"."vector", "assessment_id" "uuid", "match_count" integer DEFAULT 5) RETURNS TABLE("id" "uuid", "content" "text", "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  SELECT
    id,
    content,
    1 - (embedding <=> query_embedding) AS similarity
  FROM public.document_chunks
  WHERE document_chunks.assessment_id = match_chunks.assessment_id
  ORDER BY embedding <=> query_embedding
  LIMIT match_count;
$$;


ALTER FUNCTION "public"."match_chunks"("query_embedding" "public"."vector", "assessment_id" "uuid", "match_count" integer) OWNER TO "postgres";


